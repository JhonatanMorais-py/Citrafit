function countdownParts(now=Date.now()){
  const total=Math.max(0,Math.ceil((launchTime-now)/1000));
  return {days:Math.floor(total/86400),hours:Math.floor(total/3600)%24,minutes:Math.floor(total/60)%60,seconds:total%60,ended:now>=launchTime};
}
function updateCountdown(){
  const parts=countdownParts();
  for(const unit of ['days','hours','minutes','seconds'])document.getElementById('countdown-'+unit).textContent=String(parts[unit]).padStart(2,'0');
  const status=document.getElementById('countdown-status');
  const message=parts.ended?t('countdownEnded'):'';
  if(status.textContent!==message)status.textContent=message;
}
